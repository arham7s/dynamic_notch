import AppKit
import Observation

/// The last few bits of text you copied, for the Tray's Clipboard view.
/// Kept in memory only: nothing is written to disk, and it's gone when the app quits.
/// Off until the user turns it on, and it skips anything a password manager marks as secret.
@MainActor
@Observable
public final class ClipboardHistory {
    public struct Clip: Identifiable, Equatable, Sendable {
        public let id: UUID
        public let text: String
        public let date: Date

        public init(id: UUID = UUID(), text: String, date: Date = Date()) {
            self.id = id
            self.text = text
            self.date = date
        }
    }

    public static let capacity = 20
    /// Very long copies are cut so the history stays small.
    public static let maximumLength = 20_000
    /// Pasteboard types that mean "don't keep this" (see nspasteboard.org).
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ]

    public private(set) var clips: [Clip] = []
    /// The clip copied back most recently, for a brief "Copied" check mark.
    public private(set) var lastCopiedID: UUID?

    @ObservationIgnored private let pasteboard: NSPasteboard
    @ObservationIgnored private var lastChangeCount: Int
    @ObservationIgnored private var pollTask: Task<Void, Never>?

    public init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        lastChangeCount = pasteboard.changeCount
    }

    public var isRunning: Bool { pollTask != nil }

    /// Starts watching for new copies. What's on the clipboard already isn't recorded.
    public func start() {
        guard pollTask == nil else { return }
        lastChangeCount = pasteboard.changeCount
        pollTask = Task { [weak self] in
            while !Task.isCancelled {
                try? await Task.sleep(for: .milliseconds(800), tolerance: .milliseconds(300))
                guard !Task.isCancelled else { return }
                self?.poll()
            }
        }
    }

    /// Stops watching and forgets everything.
    public func stop() {
        pollTask?.cancel()
        pollTask = nil
        clips.removeAll()
        lastCopiedID = nil
    }

    /// Only reads the clipboard's contents when its change count moves.
    func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        let types = (pasteboard.types ?? []).map(\.rawValue)
        guard !Self.shouldIgnore(types: types), let text = pasteboard.string(forType: .string) else { return }
        record(text)
    }

    static func shouldIgnore(types: [String]) -> Bool {
        types.contains { ignoredTypes.contains($0) }
    }

    /// Adds a copy to the top. A repeat moves the old entry up instead of duplicating it.
    func record(_ text: String, at date: Date = Date()) {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        let kept = text.count > Self.maximumLength ? String(text.prefix(Self.maximumLength)) : text
        clips.removeAll { $0.text == kept }
        clips.insert(Clip(text: kept, date: date), at: 0)
        if clips.count > Self.capacity {
            clips.removeLast(clips.count - Self.capacity)
        }
    }

    /// Puts a clip back on the clipboard, ready to paste.
    public func copy(_ clip: Clip) {
        pasteboard.clearContents()
        pasteboard.setString(clip.text, forType: .string)
        // Our own write isn't a new copy.
        lastChangeCount = pasteboard.changeCount
        if let index = clips.firstIndex(where: { $0.id == clip.id }) {
            let moved = clips.remove(at: index)
            clips.insert(moved, at: 0)
        }
        lastCopiedID = clip.id
        let copiedID = clip.id
        Task { [weak self] in
            try? await Task.sleep(for: .seconds(1.2))
            if self?.lastCopiedID == copiedID { self?.lastCopiedID = nil }
        }
    }

    public func remove(_ id: UUID) {
        clips.removeAll { $0.id == id }
    }

    public func removeAll() {
        clips.removeAll()
    }
}
